#!/usr/bin/env python3
"""Resolve FireRed's four map-scoped alternate script opcodes.

These 0x50/0x52/0x54/0x56 handlers are emitted by the ELSE branches of
applymovement / waitmovement / removeobject / addobject source macros.
Map group/number arguments are generated by the separate 'map' helper macro.
Builds source-hash-backed schemas; no claim of complete handler side effects.
"""
import collections,csv,gzip,hashlib,json,re,subprocess
from pathlib import Path
ROOT=Path("upstream/pokefirered")
OUT=Path("audit-output")
PIN="ce6406d8c2eaf46d543c8a2606de0c3cb1951982"
SOURCES={
 "asm/macros/event.inc":"142ad979d7d3093244087a247fa2b4883424f77f",
 "asm/macros/map.inc":"83ef472c926ce767c9133ab9bd6922280b38bb2d"}
EXPECTED={
 "applymovement":(0x4F,0x50),
 "waitmovement":(0x51,0x52),
 "removeobject":(0x53,0x54),
 "addobject":(0x55,0x56)}
COLS=["macro","variant","opcode","opcode_hex","field_handler","macro_git_blob_sha",
 "macro_first_line","branch_header_line","map_helper_blob_sha","map_helper_line",
 "emitted_operands","emitted_widths","encoded_length_bytes","semantic_evidence"]
def sha(b):return hashlib.sha1(f"blob {len(b)}\0".encode()+b).hexdigest()
def source(path):
 b=(ROOT/path).read_bytes()
 if sha(b)!=SOURCES[path]:raise RuntimeError("Changed pinned script macro bytes "+path)
 return b.decode("utf-8","surrogateescape").splitlines()
def macros(lines):
 result={};name=None;start=None;body=[]
 for i,line in enumerate(lines,1):
  m=re.match(r"^\s*\.macro\s+([A-Za-z_]\w+)\b",line)
  if m:
   if name:raise RuntimeError("Unexpected nested macros")
   name=m.group(1);start=i;body=[]
   continue
  if re.match(r"^\s*\.endm\b",line):
   if name:result[name]=(start,body)
   name=None;start=None;body=[];continue
  if name:body.append((i,line.strip().split("@",1)[0].strip()))
 return result
def emit_path(parts,maphelper):
 out=[]
 for line,t in parts:
  m=re.match(r"^\.(byte|2byte|4byte)\s+(.+)$",t)
  if m:
   width={"byte":1,"2byte":2,"4byte":4}[m.group(1)]
   args=[a.strip() for a in m.group(2).split(",")]
   for arg in args:out.append({"line":line,"width":width,"source_expression":arg})
  elif t.startswith("map "):
   if maphelper!=[1,1]:raise RuntimeError("Map helper macro width changed")
   for index in range(2):
    out.append({"line":line,"width":1,"source_expression":t+" / helper byte "+str(index)})
  elif t:
   raise RuntimeError("Unexpected conditional branch statement "+str((line,t)))
 return out
def main():
 if subprocess.check_output(["git","-C",str(ROOT),"rev-parse","HEAD"],text=True).strip()!=PIN:
  raise RuntimeError("Wrong pinned FireRed commit")
 event=macros(source("asm/macros/event.inc"))
 mapmac=macros(source("asm/macros/map.inc"))
 if "map" not in mapmac:raise RuntimeError("Missing source-pinned two-byte map macro")
 mapline,mapbody=mapmac["map"]
 mapbyte=[x for i,t in mapbody if re.match(r"^\.byte\s+",t)]
 if len(mapbyte)!=2 or len([t for _,t in mapbody if t and not t.startswith(".byte")])!=0:
  raise RuntimeError("Map argument source macro no longer emits exactly two literal bytes")
 original=json.loads((OUT/"script_assembler_operand_summary.json").read_text())
 missing={(x["kind"],x["opcode"]) for x in original["unmapped_opcode_slots"]}
 if missing!={("FIELD",id) for name,(_,id) in EXPECTED.items()}:
  raise RuntimeError("Unexpected unresolved field script assembler opcode set "+str(missing))
 handlers={}
 with gzip.open(OUT/"bytecode_opcode_dispatch_semantic.csv.gz","rt",encoding="utf-8",newline="") as f:
  for r in csv.DictReader(f):handlers[(r["dispatch_table"],int(r["opcode"]))]=r["handler"]
 records=[]
 for name,(baseid,scopedid) in EXPECTED.items():
  start,body=event[name]
  if_idx=[k for k,(lin,t) in enumerate(body) if t==" .ifb \\map" or re.fullmatch(r"\.ifb\s+\\map",t)]
  elses=[k for k,(lin,t) in enumerate(body) if t==".else"]
  ends=[k for k,(lin,t) in enumerate(body) if t==".endif"]
  if len(if_idx)!=1 or len(elses)!=1 or len(ends)!=1 or not(if_idx[0]<elses[0]<ends[0]):
   raise RuntimeError("Map-source branch grammar changed "+name)
  if any(t.startswith(".if") for i,t in body if i!=if_idx[0]):
   raise RuntimeError("Nested map macro conditional "+name)
  btrue=body[if_idx[0]+1:elses[0]]
  bfalse=body[elses[0]+1:ends[0]]
  for label,op,branch in (("map_omitted",baseid,btrue),("map_provided",scopedid,bfalse)):
   emit=emit_path(branch,mapbyte and [1,1])
   if not emit or emit[0]["width"]!=1:raise RuntimeError("Missing opcode byte "+name)
   try:actual=int(emit[0]["source_expression"],0)
   except ValueError:raise RuntimeError("Dynamic opcode byte in "+name)
   if actual!=op:raise RuntimeError("Compiled ABI opcode mismatch "+str((name,label,actual,op)))
   if ("FIELD",op) not in handlers:raise RuntimeError("Missing field handler")
   rec={"macro":name,"variant":label,"opcode":op,"opcode_hex":hex(op),
    "field_handler":handlers[("FIELD",op)],
    "macro_git_blob_sha":SOURCES["asm/macros/event.inc"],
    "macro_first_line":start,"branch_header_line":body[if_idx[0]][0],
    "map_helper_blob_sha":SOURCES["asm/macros/map.inc"],"map_helper_line":mapline,
    "emitted_operands":json.dumps(emit,separators=(",",":")),
    "emitted_widths":",".join(str(z["width"]) for z in emit),
    "encoded_length_bytes":sum(z["width"] for z in emit),
    "semantic_evidence":"PINNED_GAS_IFB_ELSE_AND_MAP_HELPER_TWO_BYTES"}
   records.append(rec)
 with gzip.open(OUT/"script_conditional_opcode_variants.csv.gz","wt",encoding="utf-8",newline="") as f:
  w=csv.DictWriter(f,fieldnames=COLS);w.writeheader();w.writerows(records)
 rescued={("FIELD",r["opcode"]) for r in records}
 allmapped=rescued|{(x["kind"],x["opcode"]) for x in original.get("unmapped_opcode_slots",[]) if False}
 result={"script_opcode_dispatch_slots":original["original_opcode_slots"],
  "assembler_macros_initial_slots":original["opcode_slots_with_a_macro"],
  "conditional_branch_variants_resolved":len(records),
  "previously_unmapped_opcode_slots_resolved":len(rescued&missing),
  "now_macros_cover_all_461_dispatch_slots":original["opcode_slots_with_a_macro"]+len(rescued&missing)==461,
  "helper_two_byte_map_argument_verified":True,
  "source_branches":[{"macro":r["macro"],"variant":r["variant"],"opcode_hex":r["opcode_hex"],
     "bytes":r["encoded_length_bytes"]} for r in records],
  "runtime_command_handler_roles_all_verified":False,
  "full_control_flow_semantic_signoffs":0,
  "phase1_mapping_complete":False,
  "note":"Each scoped macro branch emits a distinct byte opcode; two map argument bytes are injected by the pinned map helper."}
 (OUT/"script_conditional_opcode_summary.json").write_text(json.dumps(result,indent=2,sort_keys=True)+"\n")
 print(json.dumps({k:v for k,v in result.items() if k!="source_branches"},indent=2))
 if not result["now_macros_cover_all_461_dispatch_slots"]:raise RuntimeError("Assembler opcode ABI not fully represented")
if __name__=="__main__":main()
